    logger.info("🔍 ===== TCP Ping测试 =====")
    tcp_ping_ips = test_ips_concurrently([ip for ip, _, _, _ in latency_filtered_ips])

    # 9. 带宽测试（只对筛选后的IP进行带宽测试）
    # 对通过延迟筛选的IP进行HTTP带宽测试，评估网络性能
